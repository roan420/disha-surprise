// Helper to format date nicely
export function formatDate(dateString) {
  if (!dateString) return '';
  const date = new Date(dateString + 'T00:00:00');
  if (isNaN(date.getTime())) return dateString;
  
  return date.toLocaleDateString('en-US', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  });
}

// Preset dates (e.g., this weekend, next weekend)
export function getPresetDates() {
  const today = new Date();
  const presets = [];

  // Find upcoming Saturday
  const saturday = new Date();
  const daysUntilSaturday = (6 - today.getDay() + 7) % 7 || 7;
  saturday.setDate(today.getDate() + daysUntilSaturday);

  // Upcoming Sunday
  const sunday = new Date(saturday);
  sunday.setDate(saturday.getDate() + 1);

  // Next week's Saturday
  const nextSaturday = new Date(saturday);
  nextSaturday.setDate(saturday.getDate() + 7);

  const toYMD = (d) => d.toISOString().split('T')[0];

  presets.push({
    label: 'This Saturday',
    dateValue: toYMD(saturday),
    displayDate: saturday.toLocaleDateString('en-US', { month: 'short', day: 'numeric' })
  });

  presets.push({
    label: 'This Sunday',
    dateValue: toYMD(sunday),
    displayDate: sunday.toLocaleDateString('en-US', { month: 'short', day: 'numeric' })
  });

  presets.push({
    label: 'Next Saturday',
    dateValue: toYMD(nextSaturday),
    displayDate: nextSaturday.toLocaleDateString('en-US', { month: 'short', day: 'numeric' })
  });

  return presets;
}
